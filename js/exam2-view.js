function checkSqlQ(q, code){
  if(!String(code || '').trim()) return { ok:false, kind:'info', msg:'כתבו את שאילתת ה-SQL לפני הבדיקה.' };
  if(q.kind === 'select'){
    const u = runSql(code);
    if(u.error) return { ok:false, kind:'err', msg:'שגיאה בשאילתה: ' + esc(u.error) };
    const s = runSql(q.sql);
    if(s.error) return { ok:false, kind:'err', msg:'שגיאה בפתרון המובנה: ' + esc(s.error) };
    const ordered = window.Grader.sqlOrdered(q.sql);
    const ok = u.r.columns.length === s.r.columns.length && sameRows(u.r.rows, s.r.rows, ordered);
    return { ok, kind: ok ? 'ok' : 'err', notes: u.r.notes, result: u.r, expected: s.r,
             msg: ok ? `✓ נכון! ${u.r.rows.length} שורות — זהה לפתרון הרשמי.`
                     : selectWhy(u.r, s.r, ordered, q) };
  }
  /* פקודות שינוי — משווים את מצב טבלת ההרשמות */
  const u = runSql(joinSql(q.setupSql, code, STATE_SQL));
  if(u.error) return { ok:false, kind:'err', msg:'שגיאה בפקודה: ' + esc(u.error) };
  const s = runSql(joinSql(q.setupSql, q.sql, STATE_SQL));
  if(s.error) return { ok:false, kind:'err', msg:'שגיאה בפתרון המובנה: ' + esc(s.error) };
  const ok = sameRows(u.r.rows, s.r.rows, true);
  return { ok, kind: ok ? 'ok' : 'err', notes: u.r.notes, result: u.r, expected: s.r, state:true,
           msg: ok ? `✓ נכון! מצב טבלת Enrollments אחרי הפקודה (${u.r.rows.length} שורות) זהה לפתרון הרשמי.`
                   : stateWhy(u.r.rows, s.r.rows, q) };
}

/* ---------- MongoDB ---------- */
function mongoSim(){
  const M = window.mingo;
  if(!M) return null;
  return new window.MongoSim(M, window.EXAM2.buildMongo());
}
function checkMongoQ(q, code){
  if(!String(code || '').trim()) return { ok:false, kind:'info', msg:'כתבו את פקודת המונגו לפני הבדיקה.' };
  const simU = mongoSim(), simS = mongoSim();
  if(!simU) return { ok:false, kind:'info', msg:'⚠ מנוע MongoDB עוד נטען (או שאין חיבור לאינטרנט) — נסו שוב בעוד רגע.' };

  if(q.kind === 'select'){
    const ru = simU.run(code);
    if(!ru.ok) return { ok:false, kind:'err', msg:'שגיאה בפקודה: ' + esc(ru.error) };
    const rs = simS.run(q.mongo);
    if(!rs.ok) return { ok:false, kind:'err', msg:'שגיאה בפתרון המובנה: ' + esc(rs.error) };
    const ordered = window.Grader.mongoOrdered(q.mongo);
    const ok = window.Grader.mongoSame(ru.value, rs.value, 'values', ordered);
    const un = Array.isArray(ru.value) ? ru.value.length : null;
    const sn = Array.isArray(rs.value) ? rs.value.length : null;
    return { ok, kind: ok ? 'ok' : 'err', mres: ru, expected: rs,
             msg: ok ? `✓ נכון! ${un === null ? '' : un + ' מסמכים — '}זהה לפתרון הרשמי.`
                     : mongoWhy(un, sn, ordered, q) };
  }
  /* פקודות שינוי — אותו sim: הכנה → הפקודה → קריאת המצב */
  const stateOf = (sim, userCode) => {
    if(q.setupMongo){ const r0 = sim.run(q.setupMongo); if(!r0.ok) throw new Error('הכנה: ' + r0.error); }
    const r = sim.run(userCode); if(!r.ok) throw new Error(r.error);
    const st = sim.run(STATE_MONGO); if(!st.ok) throw new Error('קריאת המצב: ' + st.error);
    return docsToRows(st.value, STATE_COLS);
  };
  let ur, sr;
  try { ur = stateOf(simU, code); } catch(e){ return { ok:false, kind:'err', msg:'שגיאה בפקודה: ' + esc(e.message) }; }
  try { sr = stateOf(simS, q.mongo); } catch(e){ return { ok:false, kind:'err', msg:'שגיאה בפתרון המובנה: ' + esc(e.message) }; }
  const ok = sameRows(ur, sr, true);
  return { ok, kind: ok ? 'ok' : 'err', stateRows: ur, expectedRows: sr, state:true,
           msg: ok ? `✓ נכון! מצב ה-collection enrollments אחרי הפקודה (${ur.length} מסמכים) זהה לפתרון הרשמי.`
                   : stateWhy(ur, sr, q) };
}

