const STATE_SQL   = `SELECT enrollmentId, studentId, offeringId, grade, enrolledAt FROM Enrollments ORDER BY enrollmentId`;
const STATE_MONGO = `db.enrollments.find({}, { _id:0, enrollmentId:1, studentId:1, offeringId:1, grade:1, enrolledAt:1 }).sort({ enrollmentId: 1 })`;
const STATE_COLS  = ['enrollmentId','studentId','offeringId','grade','enrolledAt'];

const stripSemi = s => String(s || '').trim().replace(/;+\s*$/, '');
const joinSql = (...parts) => parts.filter(p => stripSemi(p)).map(stripSemi).join(';\n') + ';';

const isDate = v => v instanceof Date || (v && typeof v === 'object' && Object.prototype.toString.call(v) === '[object Date]');
function cell(v){
  if(v === null || v === undefined) return '∅';
  if(isDate(v)) return new Date(v.getTime()).toISOString().slice(0, 10);
  if(typeof v === 'number') return String(Math.round(v * 10000) / 10000);
  const s = String(v);
  if(/^\d{4}-\d{2}-\d{2}T/.test(s)) return s.slice(0, 10);
  if(s.trim() !== '' && !isNaN(Number(s))) return String(Math.round(Number(s) * 10000) / 10000);
  return s.trim();
}
const rowKey = r => r.map(cell).join(' │ ');
/* השוואת שורות: אם אין מיון — ממוינות לפני ההשוואה */
function sameRows(a, b, ordered){
  const A = a.map(rowKey), B = b.map(rowKey);
  if(!ordered){ A.sort(); B.sort(); }
  return A.length === B.length && A.every((x, i) => x === B[i]);
}
const docsToRows = (docs, cols) => (Array.isArray(docs) ? docs : [docs]).map(d => cols.map(c => (d == null ? null : d[c])));

