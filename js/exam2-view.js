function paintScore(){
  const P = prog();
  const bOk = PART_B.filter(x => (P['b:' + x.n] || {}).sql && (P['b:' + x.n] || {}).mongo).length;
  const all = mcqQs(), pr = mcqProg();
  const aRight = all.filter(q => pr.ans[q.id] && pr.ans[q.id].ok).length;
  const el = $('#e2Score');
  if(el) el.innerHTML = `חלק א׳ (אמריקאי): <b>${aRight}/${all.length}</b> שאלות נכונות · חלק ב׳ (פתוח): <b>${bOk}/10</b> שאלות שנפתרו בשתי השפות`;
}

/* ---------- מצב מבחן ---------- */
function setExamMode(on){
  examOn = on;
  $$('#view-exam2 [data-act="sol"]').forEach(b => { b.disabled = on; b.title = on ? 'הפתרונות מוסתרים במצב מבחן' : ''; });
  if(on){
    $$('#view-exam2 [data-sol]').forEach(d => d.classList.add('hidden'));
    $$('#view-exam2 .e2-pane').forEach(d => { d.open = false; d.classList.add('e2-locked'); });
  } else {
    $$('#view-exam2 .e2-pane').forEach(d => d.classList.remove('e2-locked'));
  }
  $('#e2ExamBtn').classList.toggle('hidden', on);
  $('#e2Timer').classList.toggle('hidden', !on);
  $('#e2FinishBtn').classList.toggle('hidden', !on);
}
function tickTimer(){
  const left = Math.max(0, Math.round((examEnd - Date.now()) / 1000));
  const h = String(Math.floor(left / 3600)).padStart(2, '0');
  const m = String(Math.floor((left % 3600) / 60)).padStart(2, '0');
  const s = String(left % 60).padStart(2, '0');
  const el = $('#e2Timer'); if(el) el.textContent = `${h}:${m}:${s}`;
  if(left <= 0) finishExam(true);
}
function startExam(){
  examEnd = Date.now() + EXAM_MINUTES * 60000;
  setExamMode(true);
  tickTimer();
  clearInterval(examTick); examTick = setInterval(tickTimer, 1000);
  A().fb($('#e2ExamNote'), 'info', `⏱ מצב מבחן התחיל — ${EXAM_MINUTES} דקות. הפתרונות של חלק ב׳ ומגירות חומר הלימוד מוסתרים עד שתלחצו "סיים". זכרו: חלק א׳ — 8 מתוך 10 (6 נק' לשאלה, 48), חלק ב׳ — 7 מתוך 10 (8 נק' לשאלה, 56), סה"כ 104 ותקרה 100.`);
}
function finishExam(timeUp){
  clearInterval(examTick); examTick = null;
  setExamMode(false);
  A().fb($('#e2ExamNote'), timeUp ? 'err' : 'ok', (timeUp ? '⏰ הזמן נגמר. ' : '✓ מצב מבחן הסתיים. ') + 'הפתרונות ומגירות חומר הלימוד פתוחים שוב.');
  if($('#e2aMain') && MCQ()) renderMcqMain();   /* כדי שמגירת "חומר הנושא" תחזור */
  paintScore();
}

/* ---------- חיווט ---------- */
function wire(){
  /* חלק א׳ — שאלות אמריקאיות */
  if(MCQ() && mcqQs().length){ renderMcqTabs(); renderMcqMain(); }
  else {
    const m = $('#e2aMain');
    if(m) m.innerHTML = '<div class="card">שגיאה: בנק השאלות של חלק א׳ (exam2-mcq.js) לא נטען.</div>';
  }

  /* חלק ב׳ */
  PART_B.forEach(x => {
    const card = $(`#e2b-${x.n}`); if(!card) return;
    const taS = $('[data-in="sql"]', card), taM = $('[data-in="mongo"]', card);
    const fbS = $('[data-fb="sql"]', card), fbM = $('[data-fb="mongo"]', card);
    const resS = $('[data-res="sql"]', card), resM = $('[data-res="mongo"]', card);
    const notesS = $('[data-notes="sql"]', card);

    const mark = () => {
      const P = prog(), d = P['b:' + x.n] || {};
      ['sql','mongo'].forEach(k => {
        const el = $(`[data-mark="${k}"]`, card);
        el.classList.toggle('good', d[k] === true);
        el.classList.toggle('miss', d[k] === false);
        el.textContent = (k === 'sql' ? 'SQL ' : 'Mongo ') + (d[k] === true ? '✓' : d[k] === false ? '✗' : '');
      });
    };

    const doCheck = () => {
      A().ensureEngines().then(() => {
        const P = prog(); P['b:' + x.n] = P['b:' + x.n] || {};
        const gs = checkSqlQ(x, taS.value);
        A().fb(fbS, gs.kind, '<b>SQL:</b> ' + gs.msg);
        notesS.innerHTML = A().notesHtml(gs.notes);
        resS.innerHTML = gs.result ? `<h4>${x.kind === 'state' ? 'מצב טבלת Enrollments אצלך (SQL)' : 'התוצאה שלך (SQL)'}:</h4>` + A().resultTable(gs.result, 12) : '';
        taS.classList.toggle('ok-border', !!gs.ok); taS.classList.toggle('bad-border', gs.kind === 'err');
        P['b:' + x.n].sql = !!gs.ok;

        const gm = checkMongoQ(x, taM.value);
        A().fb(fbM, gm.kind, '<b>MongoDB:</b> ' + gm.msg);
        resM.innerHTML = gm.mres ? '<h4>התוצאה שלך (MongoDB):</h4>' + mongoOut(gm.mres)
          : (gm.stateRows ? '<h4>מצב ה-collection אצלך:</h4>' + rowsTable(gm.stateRows, STATE_COLS) : '');
        taM.classList.toggle('ok-border', !!gm.ok); taM.classList.toggle('bad-border', gm.kind === 'err');
        P['b:' + x.n].mongo = !!gm.ok;

        saveProg(); mark(); paintScore();
      });
    };

    $('[data-act="check"]', card).onclick = doCheck;
    $('[data-act="run"]', card).onclick = () => A().ensureEngines().then(() => {
      if(taS.value.trim()){
        const u = runSql(x.kind === 'state' ? joinSql(x.setupSql, taS.value, STATE_SQL) : taS.value);
        if(u.error) A().fb(fbS, 'err', '<b>SQL:</b> ' + esc(u.error));
        else { A().fb(fbS, 'info', `<b>SQL:</b> רצה בהצלחה — ${u.r.rows.length} שורות.`); notesS.innerHTML = A().notesHtml(u.r.notes);
               resS.innerHTML = '<h4>התוצאה (SQL):</h4>' + A().resultTable(u.r, 12); }
      }
      if(taM.value.trim()){
        const sim = mongoSim();
        if(!sim) return A().fb(fbM, 'info', '<b>MongoDB:</b> המנוע עוד נטען — נסו שוב בעוד רגע.');
        if(x.kind === 'state' && x.setupMongo) sim.run(x.setupMongo);
        const r = sim.run(taM.value);
        if(!r.ok) A().fb(fbM, 'err', '<b>MongoDB:</b> ' + esc(r.error));
        else {
          A().fb(fbM, 'info', '<b>MongoDB:</b> רצה בהצלחה.');
          resM.innerHTML = '<h4>התוצאה (MongoDB):</h4>' + mongoOut(r) +
            (x.kind === 'state' ? '<h4>מצב ה-collection אחרי הפקודה:</h4>' + rowsTable(docsToRows(sim.run(STATE_MONGO).value, STATE_COLS), STATE_COLS) : '');
        }
      }
    });
    $('[data-act="sol"]', card).onclick = () => {
      if(examOn) return;
      const box = $('[data-sol]', card);
      box.classList.toggle('hidden');
      $('[data-act="sol"]', card).textContent = box.classList.contains('hidden') ? '👁 הצג פתרון' : '🙈 הסתר פתרון';
    };
    $('[data-act="clear"]', card).onclick = () => {
      taS.value = ''; taM.value = '';
      taS.className = 'code-input'; taM.className = 'code-input';
      fbS.className = 'feedback'; fbM.className = 'feedback';
      resS.innerHTML = ''; resM.innerHTML = ''; notesS.innerHTML = '';
    };
    A().editorKeys(taS, doCheck); A().editorKeys(taM, doCheck);
    mark();
  });

  $('#e2ExamBtn').onclick = startExam;
  $('#e2FinishBtn').onclick = () => finishExam(false);
}

/* תצוגת פלט מונגו (JSON) ומצב טבלה */
function mongoOut(r){
  const j = v => {
    const s = JSON.stringify(v, function(k, x){ const o = this[k]; return o instanceof Date ? '__ISO__' + o.toISOString() : x; }, 2);
    return (s === undefined ? 'undefined' : s).replace(/"__ISO__([^"]+)"/g, 'ISODate("$1")');
  };
  if(Array.isArray(r.value))
    return `<div class="res-count">${r.value.length} ${r.kind === 'docs' ? 'מסמכים' : 'ערכים'}</div><pre class="json-out">${esc(j(r.value.slice(0, 12)))}</pre>` +
      (r.value.length > 12 ? `<div class="tbl-more">…ועוד ${r.value.length - 12}</div>` : '');
  if(r.kind === 'none') return `<div class="muted-sm">הפקודה רצה (אין ערך להצגה).</div>`;
  return `<pre class="json-out">${esc(j(r.value))}</pre>`;
}
function rowsTable(rows, cols){
  return `<div class="res-count">${rows.length} שורות</div><table class="result-table"><thead><tr>${
    cols.map(c => `<th>${esc(c)}</th>`).join('')}</tr></thead><tbody>${
    rows.slice(0, 12).map(r => `<tr>${r.map(c => `<td>${c === null || c === undefined ? '<span class="null">NULL</span>' : esc(cell(c))}</td>`).join('')}</tr>`).join('')
  }</tbody></table>` + (rows.length > 12 ? `<div class="tbl-more">…ועוד ${rows.length - 12} שורות</div>` : '');
}

